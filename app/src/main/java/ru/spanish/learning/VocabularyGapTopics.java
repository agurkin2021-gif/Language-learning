package ru.spanish.learning;

/** Topics for a one-request personalized audit using the existing full phone vocabulary. */
final class VocabularyGapTopics {
    private static final String PREFIX = "Аудит пробелов в словаре:";
    private static final String[][] TOPICS = {
            {"Связная речь и рассказы",
             "Хронология событий, связки предложений, причины и последствия, действия, чувства, пересказ чужих слов, вопросы и ответы."},
            {"Путешествия: аэропорт и паспортный контроль",
             "Регистрация на рейс, багаж, посадка, задержки, документы, цель поездки, сроки пребывания и ответы пограничнику."},
            {"Миграционная служба",
             "Запись на приём, документы, статус заявления, продление, разъяснения, недостающие бумаги, сроки и официальное общение."},
            {"ТВ-новости и политика",
             "Телевизионные новости: заявления, решения, выборы, законы, позиции сторон, причины событий и проверка утверждений."},
            {"Бытовое общение",
             "Просьбы, вежливый отказ, согласие, уточнение, жалобы, планы, соседи, договорённости и повседневные события."},
            {"Покупки продуктов",
             "Продукты, вес, количество, цена, срок годности, качество, обмен, просьбы к продавцу и вопросы."},
            {"Богословие и чтение Библии",
             "Библейские повествования, историческая последовательность, действия персонажей, вера, пророчества, молитва и обсуждение текста."},
            {"Салон красоты: общение с мастером",
             "Стрижка, укладка, длина, цвет, состояние волос, материалы, корректировки и объяснение результата мастеру."},
            {"Доктор и здоровье",
             "Описание симптомов и их начала, боль, длительность, обследование, запись, назначения и уточнения врачу."},
            {"Школа и дети",
             "Общение с учителем, посещаемость, домашняя работа, расписание, поведение, оценки, документы и родительские вопросы."},
            {"Животные",
             "Домашние и дикие животные, поведение, кормление, уход, прогулка, здоровье и описание событий с животными."},
            {"Туризм и отдых",
             "Отель, заселение, бронирование, экскурсии, пляж, транспорт, планы, впечатления и проблемы."},
            {"Спорт: волейбол",
             "Подача, приём, пас, удар, блок, счёт, позиции, командные указания, описание игры и результатов."}
    };

    private VocabularyGapTopics() {}

    static String[] names() {
        String[] result = new String[TOPICS.length];
        for (int i = 0; i < TOPICS.length; i++) result[i] = TOPICS[i][0];
        return result;
    }

    static boolean isGapAnalysis(String request) {
        return request != null && request.startsWith(PREFIX);
    }

    static String prompt(int index, boolean english) {
        if (index < 0 || index >= TOPICS.length)
            throw new IllegalArgumentException("Неизвестная тема");
        return PREFIX + " «" + TOPICS[index][0] + "».\n"
                + "Изучаемый язык: "
                + (english ? "английский." : "аргентинский испанский (Rioplatense, vos/tenés).")
                + "\nНужные ситуации: " + TOPICS[index][1] + "\n"
                + "Проведи персональный анализ ВСЕГО моего словаря: сравни реально "
                + "освоенные и ещё изучаемые слова и выражения с речевыми потребностями "
                + "этой темы. Сначала мысленно найди самые критичные пробелы. "
                + "Особенно важны готовые разговорные конструкции, хронология, "
                + "причины, последствия и естественные связки для пересказа событий. "
                + "Выбирай по реальной частоте и полезности, а не по алфавиту; "
                + "редкие термины не ставь выше необходимых повседневных фраз.\n"
                + "Добавь максимум 10 новых слов и устойчивых выражений, "
                + "только если их действительно не хватает. Слова, которые есть "
                + "в изучении или уже освоены, не добавляй; избегай почти "
                + "тождественных по смыслу повторов. Не создавай рассказ сейчас: "
                + "мы собираем лексику для будущих рассказов и разговоров.\n"
                + (english ? ""
                    : "Испанские учебные выражения — только естественные готовые "
                    + "разговорные формы, никаких инфинитивных заготовок как основной формы. "
                    + "Зависимый инфинитив внутри полноценной фразы допустим. "
                    + "Используй vos/tenés и живую речь Буэнос-Айреса.\n")
                + "Союзы, наречия, местоименные связки и вводные конструкции "
                + "оформляй как полезные цельные выражения, не выдавай их "
                + "за существительные/прилагательные. Проверяй точный русский "
                + "перевод и значение каждого кандидата. По одному сохраняй "
                + "карточки с подходящим эмодзи или смысловым SVG. "
                + "Если важных новых единиц меньше десяти — сохрани меньше. "
                + "Не заявляй о сохранении без результата инструмента. "
                + "Каждая новая карточка проходит три независимых аудита перевода "
                + "до сохранения. Главный русский перевод всегда ДОСЛОВНЫЙ и "
                + "сохраняет лицо, время и частицы. Если буквальный перевод "
                + "звучит коряво, после него в скобках кратко укажи смысловой "
                + "вариант. Не заменяй дословный перевод смысловым.";
    }
}
